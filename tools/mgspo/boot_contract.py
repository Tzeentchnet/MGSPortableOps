#!/usr/bin/env python3
"""Generate the standalone C contract from measured PPSSPP boot state."""

import argparse
from datetime import datetime, timedelta, timezone
import hashlib
import json
from pathlib import Path
import struct
import sys

import oracle


def build_prepared_stack(start):
    stack_start = start["stack_start"]
    stack_size = start["stack_size"]
    stack_end = stack_start + stack_size
    data = bytearray(b"\xff" * stack_size)

    def offset(address, size):
        relative = address - stack_start
        if relative < 0 or relative + size > stack_size:
            raise oracle.OracleError(
                f"prepared stack write 0x{address:08x}+{size} is outside "
                f"0x{stack_start:08x}-0x{stack_end:08x}"
            )
        return relative

    def write_u32(address, value):
        relative = offset(address, 4)
        struct.pack_into("<I", data, relative, value)

    k0 = start["initial_k0"]
    k0_offset = offset(k0, 0x100)
    data[k0_offset:k0_offset + 0x100] = b"\x00" * 0x100
    write_u32(stack_start, start["uid"])
    write_u32(k0 + 0xC0, start["uid"])
    write_u32(k0 + 0xC8, stack_start)
    write_u32(k0 + 0xF8, 0xFFFFFFFF)
    write_u32(k0 + 0xFC, 0xFFFFFFFF)

    argument = bytes.fromhex(start["argument_hex"])
    argument_offset = offset(start["argument_address"], len(argument))
    data[argument_offset:argument_offset + len(argument)] = argument

    digest = hashlib.sha256(data).hexdigest()
    if digest != start["prepared_stack_sha256"]:
        raise oracle.OracleError(
            "reconstructed start-thread stack SHA-256 "
            f"{digest} != {start['prepared_stack_sha256']}"
        )
    return bytes(data)


def _c_string(value):
    return json.dumps(value, ensure_ascii=True)


def _u32(value):
    return f"UINT32_C(0x{value:08x})"


def render_header(config):
    start = config.module["start_thread"]
    build_prepared_stack(start)
    argument = bytes.fromhex(start["argument_hex"])
    if not argument or argument[-1] != 0 or b"\0" in argument[:-1]:
        raise oracle.OracleError(
            "module.start_thread.argument_hex must be one NUL-terminated "
            "string"
        )
    argument_text = argument[:-1].decode("ascii")
    rtc = datetime.fromtimestamp(
        config.settings["rtc_epoch_seconds"],
        timezone.utc,
    ) + timedelta(minutes=config.settings["timezone_minutes"])
    controls = ", ".join(_u32(value) for value in start["initial_vfpu_control"])
    argument_bytes = ", ".join(f"0x{value:02x}" for value in argument)

    lines = [
        "/* Generated by tools/mgspo/boot_contract.py. Do not edit. */",
        "#ifndef MGSPO_BOOT_CONTRACT_H",
        "#define MGSPO_BOOT_CONTRACT_H",
        "",
        "#include <stdint.h>",
        "",
        '#define MGSPO_GAME_TITLE "Metal Gear Solid: Portable Ops"',
        '#define MGSPO_BOOT_IMAGE "mgspo_image.bin"',
        f"#define MGSPO_MODULE_BASE {_u32(config.module['base'])}",
        f"#define MGSPO_MODULE_ENTRY {_u32(config.module['entry'])}",
        f"#define MGSPO_MODULE_GP {_u32(config.module['gp'])}",
        f"#define MGSPO_MODULE_IMAGE_SIZE {_u32(config.module['image_size'])}",
        f"#define MGSPO_MODULE_UID {_u32(start['module_uid'])}",
        f"#define MGSPO_START_UID {_u32(start['uid'])}",
        f"#define MGSPO_START_PRIORITY {_u32(start['priority'])}",
        f"#define MGSPO_STACK_START {_u32(start['stack_start'])}",
        f"#define MGSPO_STACK_SIZE {_u32(start['stack_size'])}",
        f"#define MGSPO_START_ATTR {_u32(start['attr'])}",
        f"#define MGSPO_EFFECTIVE_ATTR {_u32(start['effective_attr'])}",
        f"#define MGSPO_NEXT_UID {_u32(start['next_uid'])}",
        f"#define MGSPO_INITIAL_GE_LIST_ID {_u32(start['initial_ge_list_id'])}",
        f"#define MGSPO_INITIAL_HCOUNT {_u32(start['initial_hcount'])}",
        f"#define MGSPO_ARGUMENT_ADDRESS {_u32(start['argument_address'])}",
        f"#define MGSPO_ARGUMENT_SIZE UINT32_C({len(argument)})",
        f"#define MGSPO_INITIAL_SP {_u32(start['initial_sp'])}",
        f"#define MGSPO_INITIAL_K0 {_u32(start['initial_k0'])}",
        f"#define MGSPO_INITIAL_RA {_u32(start['initial_ra'])}",
        f"#define MGSPO_INITIAL_GPR_FILL {_u32(start['initial_gpr_fill'])}",
        f"#define MGSPO_INITIAL_HI {_u32(start['initial_hi'])}",
        f"#define MGSPO_INITIAL_LO {_u32(start['initial_lo'])}",
        f"#define MGSPO_INITIAL_FCR31 {_u32(start['initial_fcr31'])}",
        f"#define MGSPO_INITIAL_FPCOND {_u32(start['initial_fpcond'])}",
        f"#define MGSPO_INITIAL_FPR_FILL {_u32(start['initial_fpr_fill_bits'])}",
        f"#define MGSPO_INITIAL_VFPU_FILL {_u32(start['initial_vfpu_fill_bits'])}",
        f"#define MGSPO_TRACE_STEPS UINT64_C({config.trace_steps})",
        (
            "#define MGSPO_RTC_UNIX_EPOCH "
            f"INT64_C({config.settings['rtc_epoch_seconds']})"
        ),
        f"#define MGSPO_RTC_YEAR UINT16_C({rtc.year})",
        f"#define MGSPO_RTC_MONTH UINT16_C({rtc.month})",
        f"#define MGSPO_RTC_DAY UINT16_C({rtc.day})",
        f"#define MGSPO_RTC_HOUR UINT16_C({rtc.hour})",
        f"#define MGSPO_RTC_MINUTE UINT16_C({rtc.minute})",
        f"#define MGSPO_RTC_SECOND UINT16_C({rtc.second})",
        (
            "#define MGSPO_PREPARED_STACK_SHA256 "
            f"{_c_string(start['prepared_stack_sha256'])}"
        ),
        "",
        f"#define SR_GAME_TITLE MGSPO_GAME_TITLE",
        f"#define SR_BOOT_ARG {_c_string(argument_text)}",
        "#define SR_BOOT_NEXT_UID MGSPO_NEXT_UID",
        "#define SR_INITIAL_GE_LIST_ID MGSPO_INITIAL_GE_LIST_ID",
        "#define SR_MODULE_START_UID MGSPO_START_UID",
        "#define SR_MODULE_START_PRIORITY MGSPO_START_PRIORITY",
        "#define SR_MODULE_START_STACK_SIZE MGSPO_STACK_SIZE",
        "#define SR_MODULE_START_ATTR MGSPO_EFFECTIVE_ATTR",
        "#define SR_CONFIG_BOOT_IMAGE MGSPO_BOOT_IMAGE",
        "#define SR_CONFIG_BOOT_BASE MGSPO_MODULE_BASE",
        "#define SR_CONFIG_BOOT_ENTRY MGSPO_MODULE_ENTRY",
        (
            "#define SR_EXPECTED_ISO_SIZE "
            f"UINT64_C({config.disc['iso_size']})"
        ),
        (
            "#define SR_EXPECTED_ISO_SHA1 "
            f"{_c_string(config.disc['iso_sha1'])}"
        ),
        "#define SR_MODULE_POLICY_INIT sr_mgspo_register_module_policy",
        "",
        "#define MGSPO_INITIAL_VFPU_CONTROL_VALUES \\",
        f"    {{ {controls} }}",
        "#define MGSPO_BOOT_ARGUMENT_BYTES \\",
        f"    {{ {argument_bytes} }}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def write_if_changed(path, content):
    encoded = content.encode("ascii")
    if path.is_file() and path.read_bytes() == encoded:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encoded)
    return True


def parse_args(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--config",
        type=Path,
        default=oracle.DEFAULT_CONFIG,
    )
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    try:
        config = oracle.load_config(args.config)
        if not config.module["start_thread"]["verified"]:
            raise oracle.OracleError(
                "module.start_thread must be verified before generating "
                "the standalone contract"
            )
        changed = write_if_changed(args.output, render_header(config))
    except (OSError, UnicodeError, oracle.OracleError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2
    print(
        f"{'wrote' if changed else 'verified'} {args.output.resolve()}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
